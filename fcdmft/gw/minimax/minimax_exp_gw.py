def get_exp_minimax_coeff_gw(k, E_range):
    if k == 26:
        E_ratio, aw = get_coeff_26(E_range)
    elif k == 28:
        E_ratio, aw = get_coeff_28(E_range)
    elif k == 30:
        E_ratio, aw = get_coeff_30(E_range)
    elif k == 32:
        E_ratio, aw = get_coeff_32(E_range)
    elif k == 34:
        E_ratio, aw = get_coeff_34(E_range)
        
    aw = rescale_grid(aw, E_ratio)
    tau = aw[:k]
    tau_weight = aw[k:]
    return tau, tau_weight


def rescale_grid(aw, E_ratio):
    aw = numpy.asarray(aw)
    E_ratio = E_ratio / 1.5 if E_ratio > 1.5 else 1.0
    aw = aw * E_ratio
    return aw


